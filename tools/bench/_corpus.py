def make_docs(n: int, paragraphs_each: int = 5) -> list[str]:
    """組出 n 筆文件，每筆串接 paragraphs_each 個段落。

    paragraphs_each=1 約 60 token、2 約 120、5 約 290 —— 最後一個接近真實切塊長度。
    """
    return [
        "".join(PARAGRAPHS[(i + j) % len(PARAGRAPHS)] for j in range(paragraphs_each))
        for i in range(n)
    ]
